/**
 * gen-dispatch.mjs — Generate a C dispatch.c that multiplexes ViennaRNA
 * CLI programs into a single WASI binary, routing on argv[1].
 *
 * Library usage:
 *   import { generateDispatch } from './gen-dispatch.mjs'
 *   const cSource = generateDispatch(tools)
 *
 * CLI usage (from any directory):
 *   node build/wasi/gen-dispatch.mjs
 *   → reads ./tools.json (relative to this script) and writes dispatch.c
 *     next to it.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

/**
 * Generate a C dispatch source that routes argv[1] to the matching
 * <tool>_main(argc-1, argv+1) for every tool in the registry.
 *
 * @param {Array<{name: string, source: string}>} tools
 * @returns {string} Complete dispatch.c source text
 */
export function generateDispatch(tools) {
  const lines = []

  // Headers
  lines.push('/* Auto-generated by gen-dispatch.mjs — DO NOT EDIT */')
  lines.push('#include <string.h>')
  lines.push('#include <stdio.h>')
  lines.push('')

  // Forward declarations
  for (const tool of tools) {
    lines.push(`int ${tool.name}_main(int, char **);`)
  }
  lines.push('')

  // main
  lines.push('int main(int argc, char **argv) {')

  // argc < 2 fallback — print tool list to stderr and exit 1
  lines.push('  if (argc < 2) {')
  lines.push('    fprintf(stderr, "Usage: viennarna <tool> [args...]\\n");')
  lines.push('    fprintf(stderr, "Available tools:\\n");')
  for (const tool of tools) {
    lines.push(`    fprintf(stderr, "  ${tool.name}\\n");`)
  }
  lines.push('    return 1;')
  lines.push('  }')
  lines.push('')

  // Routing branches
  for (let i = 0; i < tools.length; i++) {
    const kw = i === 0 ? 'if' : '} else if'
    lines.push(`  ${kw} (!strcmp(argv[1], "${tools[i].name}")) {`)
    lines.push(`    return ${tools[i].name}_main(argc - 1, argv + 1);`)
  }
  lines.push('  }')
  lines.push('')

  // Unknown tool fallback
  lines.push('  fprintf(stderr, "Unknown tool: %s\\n", argv[1]);')
  lines.push('  fprintf(stderr, "Available tools:\\n");')
  for (const tool of tools) {
    lines.push(`  fprintf(stderr, "  ${tool.name}\\n");`)
  }
  lines.push('  return 1;')
  lines.push('}')
  lines.push('')

  return lines.join('\n')
}

// CLI mode — invoked directly as `node gen-dispatch.mjs`
const scriptPath = fileURLToPath(import.meta.url)
const isMain = process.argv[1] === scriptPath

if (isMain) {
  const scriptDir = dirname(scriptPath)
  const toolsPath = join(scriptDir, 'tools.json')
  const outPath = join(scriptDir, 'dispatch.c')

  const tools = JSON.parse(readFileSync(toolsPath, 'utf8'))
  const src = generateDispatch(tools)
  writeFileSync(outPath, src)
  console.log(`Wrote ${outPath} (${tools.length} tools)`)
}
